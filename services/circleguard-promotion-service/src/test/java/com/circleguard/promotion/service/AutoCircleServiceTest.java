package com.circleguard.promotion.service;

import com.circleguard.promotion.model.graph.CircleNode;
import com.circleguard.promotion.repository.graph.CircleNodeRepository;
import com.circleguard.promotion.repository.graph.UserNodeRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.List;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

@ExtendWith(MockitoExtension.class)
class AutoCircleServiceTest {

    @Mock
    private UserNodeRepository userRepository;

    @Mock
    private CircleNodeRepository circleRepository;

    @Mock
    private CircleService circleService;

    private AutoCircleService autoCircleService;

    @BeforeEach
    void setUp() {
        autoCircleService = new AutoCircleService(userRepository, circleRepository, circleService);
    }

    @ParameterizedTest
    @MethodSource("invalidEncounterPairs")
    void evaluateEncounter_WithInvalidUsers_DoesNothing(String userA, String userB) {
        autoCircleService.evaluateEncounter(userA, userB);

        verifyNoInteractions(userRepository, circleRepository, circleService);
    }

    @Test
    void evaluateEncounter_WithNullDuration_DoesNothing() {
        when(userRepository.getCumulativeEncounterDuration("user-a", "user-b")).thenReturn(null);

        autoCircleService.evaluateEncounter("user-a", "user-b");

        verifyNoInteractions(circleRepository, circleService);
    }

    @Test
    void evaluateEncounter_BelowThreshold_DoesNothing() {
        when(userRepository.getCumulativeEncounterDuration("user-a", "user-b")).thenReturn(3599L);

        autoCircleService.evaluateEncounter("user-a", "user-b");

        verifyNoInteractions(circleRepository, circleService);
    }

    @Test
    void evaluateEncounter_AtThreshold_CreatesAutoCircleAndJoinsBothUsers() {
        when(userRepository.getCumulativeEncounterDuration("user-a", "user-b")).thenReturn(3600L);
        when(circleRepository.findCommonCircles("user-a", "user-b")).thenReturn(List.of());
        when(circleRepository.save(any(CircleNode.class))).thenAnswer(invocation -> invocation.getArgument(0));

        autoCircleService.evaluateEncounter("user-a", "user-b");

        ArgumentCaptor<CircleNode> circleCaptor = ArgumentCaptor.forClass(CircleNode.class);
        verify(circleRepository).save(circleCaptor.capture());
        CircleNode circle = circleCaptor.getValue();
        assertTrue(circle.getName().startsWith("Auto Mesh "));
        assertTrue(circle.getInviteCode().startsWith("AUTO-"));
        assertEquals(Boolean.TRUE, circle.getIsActive());
        assertEquals(Boolean.TRUE, circle.getIsAutoGenerated());
        assertNotNull(circle.getCreatedAt());
        verify(circleService).joinCircle("user-a", circle.getInviteCode());
        verify(circleService).joinCircle("user-b", circle.getInviteCode());
    }

    @Test
    void evaluateEncounter_WhenUsersAlreadyShareAutoCircle_DoesNothing() {
        when(userRepository.getCumulativeEncounterDuration("user-a", "user-b")).thenReturn(3600L);
        CircleNode autoCircle = CircleNode.builder().isAutoGenerated(true).build();
        when(circleRepository.findCommonCircles("user-a", "user-b")).thenReturn(List.of(autoCircle));

        autoCircleService.evaluateEncounter("user-a", "user-b");

        verify(circleRepository, never()).save(any(CircleNode.class));
        verify(circleService, never()).joinCircle(anyString(), anyString());
    }

    private static Stream<Arguments> invalidEncounterPairs() {
        return Stream.of(
                Arguments.of(null, "user-b"),
                Arguments.of("user-a", null),
                Arguments.of("user-a", "user-a"));
    }
}
